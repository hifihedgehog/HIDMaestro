# Builds the case 5 driver harnesses: driver_harness_oracle.exe and
# driver_harness_tree.exe.
#
# Each compiles the UMDF2 driver (driver.c with driver.h) and the XUSB
# companion (companion.c) natively, unmodified, with the harness under
# harness\ and the stand-in headers under stubs\. The oracle harness takes
# 9bd6279's sources, kept byte for byte in oracle\ and checked here against
# their blob ids. The tree harness takes the repository's driver\. One
# script, one set of flags, so the two differ only in the driver sources.
#
# The compiler and kits are the ones the driver build uses
# (scripts\native_env.cmd, scripts\build.cmd, scripts\build_companion.cmd):
# the Windows SDK and WDK of HM_SDK_ROOT / HM_WDK_ROOT or the installed kit,
# version HM_WDK_VERSION or 10.0.26100.0, the UMDF 2.15 headers, and the
# newest Visual Studio with the x64 C++ tools as vswhere finds it. The
# driver sources get build.cmd's defines and warning flags. Nothing links
# WdfDriverStubUm.lib: the harness defines WdfFunctions_02015 and
# WdfDriverGlobals itself (wdf.h:69-72, wdffuncenum.h:21). Every Win32 call
# the drivers make goes to the harness through stubs\hm_fi.h, and the build
# fails if a compiled driver object still imports anything from a system
# DLL.
#
# Usage: build.ps1 -Out <dir> [-Obj <dir>] [-Repo <worktree root>]
param(
    [Parameter(Mandatory = $true)][string]$Out,
    [string]$Obj,
    [string]$Repo
)
$ErrorActionPreference = 'Stop'
$Out = [IO.Path]::GetFullPath($Out)
# Windows PowerShell 5.1 leaves $PSScriptRoot empty in parameter defaults.
if (-not $Repo) { $Repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..\..\..')).Path }
if (-not $Obj) { $Obj = Join-Path $PSScriptRoot '..\obj\driver_harness' }
$Obj = [IO.Path]::GetFullPath($Obj)

# 9bd6279's blobs. oracle\.gitattributes keeps git from converting them.
$oracleBlobs = [ordered]@{
    'driver.c'    = '91496e4ac1c41dcdbf165fb24f92ac3c637584a6'
    'driver.h'    = '412bfeccf2f8d326aa2d5582331978b37098021d'
    'companion.c' = '5cc3a4870bcc6b16103dfd772bc1de44977afc84'
}

function BlobId([string]$path) {
    # --no-filters hashes the bytes on disk, whatever core.autocrlf says.
    $id = (& git -C $Repo hash-object --no-filters -- $path)
    if ($LASTEXITCODE -ne 0) { throw "git hash-object $path failed." }
    return $id.Trim()
}

$oracleDir = Join-Path $PSScriptRoot 'oracle'
foreach ($name in $oracleBlobs.Keys) {
    $got = BlobId (Join-Path $oracleDir $name)
    if ($got -ne $oracleBlobs[$name]) {
        throw "oracle\$name is blob $got, not 9bd6279's $($oracleBlobs[$name]). Write it again with git show 9bd6279:driver/$name."
    }
}

# Kits, as native_env.cmd chooses them.
$sdkRoot = $env:HM_SDK_ROOT
if (-not $sdkRoot) { $sdkRoot = $env:WindowsSdkDir }
if (-not $sdkRoot) { $sdkRoot = Join-Path ${env:ProgramFiles(x86)} 'Windows Kits\10' }
$wdkRoot = $env:HM_WDK_ROOT
if (-not $wdkRoot) { $wdkRoot = $env:WDKContentRoot }
if (-not $wdkRoot) { $wdkRoot = $sdkRoot }
$kit = $env:HM_WDK_VERSION
if (-not $kit) { $kit = $env:Version_Number }
if (-not $kit) { $kit = '10.0.26100.0' }
$sdkRoot = $sdkRoot.TrimEnd('\')
$wdkRoot = $wdkRoot.TrimEnd('\')
$umInc = "$sdkRoot\Include\$kit\um"
$sharedInc = "$sdkRoot\Include\$kit\shared"
$ucrtInc = "$sdkRoot\Include\$kit\ucrt"
$kmInc = "$wdkRoot\Include\$kit\km"
$wdfInc = "$wdkRoot\Include\wdf\umdf\2.15"
foreach ($f in "$umInc\windows.h", "$sharedInc\sdkddkver.h", "$kmInc\hidport.h", "$wdfInc\wdf.h", "$wdfInc\wdffuncenum.h") {
    if (-not (Test-Path $f)) { throw "Kit file missing: $f. Set HM_SDK_ROOT, HM_WDK_ROOT or HM_WDK_VERSION as for scripts\build.cmd." }
}

$installer = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio\Installer'
$vswhere = Join-Path $installer 'vswhere.exe'
# vcvars64.bat runs vswhere from PATH.
$env:PATH = "$installer;$env:PATH"
$vs = & $vswhere -latest -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -property installationPath
if (-not $vs) { throw 'No Visual Studio with the x64 C++ tools.' }
$vcvars = Join-Path $vs 'VC\Auxiliary\Build\vcvars64.bat'

New-Item -ItemType Directory -Force -Path $Out, $Obj | Out-Null
$stubs = Join-Path $PSScriptRoot 'stubs'
$harnessDir = Join-Path $PSScriptRoot 'harness'

# The WDF function names for the harness's trap table, from the kit's own
# enum, so an entry the drivers reach unimplemented stops the run with
# its index and name.
$enumText = Get-Content -Raw (Join-Path $wdfInc 'wdffuncenum.h')
$entries = [regex]::Matches($enumText, '(?m)^\s*(\w+)TableIndex\s*=\s*(\d+),')
$count = [int]([regex]::Match($enumText, 'WdfFunctionTableNumEntries\s*=\s*(\d+)').Groups[1].Value)
if ($entries.Count -ne $count) { throw "wdffuncenum.h lists $($entries.Count) functions, WdfFunctionTableNumEntries is $count." }
$names = New-Object System.Text.StringBuilder
[void]$names.Append("/* Generated by build.ps1 from $wdfInc\wdffuncenum.h. */`n")
for ($i = 0; $i -lt $entries.Count; $i++) {
    if ([int]$entries[$i].Groups[2].Value -ne $i) { throw "wdffuncenum.h is not in index order at $i." }
    [void]$names.Append("HM_WDF_FN($($entries[$i].Groups[1].Value), $i)`n")
}
$genDir = Join-Path $Obj 'generated'
New-Item -ItemType Directory -Force -Path $genDir | Out-Null
[IO.File]::WriteAllText((Join-Path $genDir 'wdf_names.h'), $names.ToString(), (New-Object System.Text.ASCIIEncoding))

# A stand-in for build\version_gen.h, which scripts\gen_version.ps1 writes
# from Directory.Build.props. Fixed at 9bd6279's version, 1.13.0, so both
# harnesses announce the same driver version whatever the tree's props say.
$versionGen = @"
/* Generated by the driver harness's build.ps1: a fixed stand-in for
   build\version_gen.h (scripts\gen_version.ps1). */
#pragma once
#define HM_VER_MAJOR  1
#define HM_VER_MINOR  13
#define HM_VER_PATCH  0
#define HM_VER_STRING "1.13.0.0"
"@
[IO.File]::WriteAllText((Join-Path $genDir 'version_gen.h'), $versionGen.Replace("`r`n", "`n") + "`n", (New-Object System.Text.ASCIIEncoding))

# build.cmd's flags for the drivers (scripts\build.cmd:47-57), the forced
# include in front. The harness gets the same defines.
$defines = '/D _AMD64_ /D _WIN64 /D UNICODE /D _UNICODE /D UMDF_VERSION_MAJOR=2 /D UMDF_VERSION_MINOR=15'
$includes = "`"/I$stubs`" `"/I$harnessDir`" `"/I$genDir`" `"/I$umInc`" `"/I$sharedInc`" `"/I$ucrtInc`" `"/I$kmInc`" `"/I$wdfInc`""
$driverFlags = "/nologo /W4 /GS /Gz /wd4324 /MT $defines /FIhm_fi.h $includes"
$harnessFlags = "/nologo /W4 /GS /O2 /wd4324 /MT $defines $includes"

$harnessFiles = Get-ChildItem -File $harnessDir -Filter *.c | Sort-Object Name
$ownFiles = @(Get-ChildItem -File $harnessDir, $stubs | Sort-Object FullName) + @(Get-Item $PSCommandPath)
$ownHash = ($ownFiles | Get-FileHash -Algorithm SHA256 | ForEach-Object Hash) -join ''

$flavors = @(
    @{ Name = 'oracle'; Dir = $oracleDir },
    @{ Name = 'tree'; Dir = (Join-Path $Repo 'driver') }
)

foreach ($f in $flavors) {
    $exe = Join-Path $Out "driver_harness_$($f.Name).exe"
    $stampPath = Join-Path $Out "driver_harness_$($f.Name).stamp"
    $sources = @('driver.c', 'driver.h', 'companion.c') | ForEach-Object { Join-Path $f.Dir $_ }
    foreach ($s in $sources) { if (-not (Test-Path $s)) { throw "Driver source missing: $s" } }
    # The tree's drivers share hm_contract.h, which 9bd6279 lacks.
    $contractH = Join-Path $f.Dir 'hm_contract.h'
    if (Test-Path $contractH) { $sources += $contractH }
    $srcIds = ($sources | ForEach-Object { BlobId $_ }) -join ' '
    $stamp = "$srcIds $ownHash $kit $vs"
    if ((Test-Path $exe) -and (Test-Path $stampPath) -and ((Get-Content $stampPath -Raw).Trim() -eq $stamp)) {
        Write-Host "driver_harness_$($f.Name).exe is current"
        continue
    }

    $work = Join-Path $Obj $f.Name
    if (Test-Path $work) { Remove-Item -Recurse -Force $work }
    New-Item -ItemType Directory -Force -Path $work | Out-Null
    $driverC = Join-Path $f.Dir 'driver.c'
    $companionC = Join-Path $f.Dir 'companion.c'
    $harnessList = ($harnessFiles | ForEach-Object { '"' + $_.FullName + '"' }) -join ' '
    $symbols = Join-Path $work 'symbols.txt'
    # The identity tag as the flavor's own driver.h computes it, for the
    # harness's vector stream (hm_case_identity.c). 9bd6279's driver.h has
    # no tag, and its unit says so.
    $tagC = Join-Path $work 'driver_tag.c'
    # The tag lives in driver.h, or in hm_contract.h, which driver.h
    # includes, from lane DD-3 on.
    $hasTag = @('driver.h', 'hm_contract.h') | Where-Object { Test-Path (Join-Path $f.Dir $_) } |
        Where-Object { (Get-Content (Join-Path $f.Dir $_) -Raw) -match 'HmIdentityTag' } | Select-Object -First 1
    $tagSource = if ($hasTag) {
        "#include `"driver.h`"`nint HmDriverHasIdentityTag = 1;`nunsigned long long HmDriverIdentityTag(const unsigned short *t) { return HmIdentityTag((const WCHAR *)t); }`n"
    } else {
        "int HmDriverHasIdentityTag = 0;`nunsigned long long HmDriverIdentityTag(const unsigned short *t) { (void)t; return 0; }`n"
    }
    [IO.File]::WriteAllText($tagC, $tagSource, (New-Object System.Text.ASCIIEncoding))
    # Both drivers define DriverEntry, so the companion's is renamed.
    $cmd = @"
@echo off
call "$vcvars" >nul || exit /b 1
cl $driverFlags "/Fo$work\driver.obj" /c "$driverC" || exit /b 1
cl $driverFlags /DDriverEntry=CompanionDriverEntry "/Fo$work\companion.obj" /c "$companionC" || exit /b 1
cl $driverFlags "/I$($f.Dir)" "/Fo$work\driver_tag.obj" /c "$tagC" || exit /b 1
dumpbin /nologo /symbols "$work\driver.obj" "$work\companion.obj" > "$symbols" || exit /b 1
cl $harnessFlags "/Fo$work\\" /c $harnessList || exit /b 1
link /nologo /SUBSYSTEM:CONSOLE "/OUT:$exe" "$work\driver.obj" "$work\companion.obj" "$work\driver_tag.obj" $(($harnessFiles | ForEach-Object { '"' + (Join-Path $work ($_.BaseName + '.obj')) + '"' }) -join ' ') kernel32.lib advapi32.lib || exit /b 1
"@
    $cmdPath = Join-Path $work 'build.cmd'
    Set-Content -Path $cmdPath -Value $cmd -Encoding ascii
    $p = Start-Process -FilePath $env:ComSpec -ArgumentList '/d', '/c', "`"$cmdPath`"" -NoNewWindow -PassThru `
        -RedirectStandardOutput (Join-Path $work 'build.log') -RedirectStandardError (Join-Path $work 'build.err')
    # Reading the handle now keeps the exit code readable after the wait.
    $null = $p.Handle
    $p.WaitForExit()
    if ($p.ExitCode -ne 0) {
        Get-Content (Join-Path $work 'build.log'), (Join-Path $work 'build.err') | Select-Object -Last 60 | Write-Host
        throw "Building driver_harness_$($f.Name).exe failed (exit $($p.ExitCode))."
    }

    # No driver object may import from a system DLL: every external it
    # names is the harness's (Hm*, WdfFunctions_02015, WdfDriverGlobals) or
    # the C runtime's.
    $imports = Get-Content $symbols | Where-Object { $_ -match 'UNDEF.*External\s+\|\s+(__imp_\S+)' } | ForEach-Object { $Matches[1] } | Sort-Object -Unique
    if ($imports) {
        Remove-Item -Force $exe -ErrorAction SilentlyContinue
        throw "The $($f.Name) driver objects import from system DLLs, which hm_fi.h must redirect: $($imports -join ', ')"
    }
    Set-Content -Path $stampPath -Value $stamp -Encoding ascii
    Write-Host "built driver_harness_$($f.Name).exe from $($f.Dir)"
}
